def grade(Hn, X, Y, FIXED, drive, bank, court, fill, cut=None):
    """drive, bank, court: the 과학관 drive, its bank and court (polygons); cut: the half-plane south of the drive's north
    arm.  Returns the nodes set (to be FIXED) and a summary"""
    P = np.array(PTS)
    zt = P[:, 2] + BIAS + datum.tilt(P[:, 0], P[:, 1])            # (on the working datum)
    gx = X[0, :]; gy = Y[:, 0]
    st = gx[1] - gx[0]
    fi = (P[:, 0] - gx[0]) / st; fj = (P[:, 1] - gy[0]) / st
    i0 = np.floor(fi).astype(int); j0 = np.floor(fj).astype(int); tx = fi - i0; ty = fj - j0
    g = (Hn[j0, i0] * (1 - tx) * (1 - ty) + Hn[j0, i0 + 1] * tx * (1 - ty) + Hn[j0 + 1, i0] * (1 - tx) * ty +
         Hn[j0 + 1, i0 + 1] * tx * ty)
    d = zt - g
    lay = unary_union([drive.intersection(cut) if cut is not None else drive, SE])
    # (the drive and the bank were laid over the court as first levelled, whose nodes are FIXED: they move here)
    keep = shapely.contains_xy(unary_union([court.buffer(0.5), KEEP]), X, Y) | (FIXED & ~shapely.contains_xy(unary_union([drive, bank]), X, Y))
    core = shapely.contains_xy(lay, X, Y) & ~keep
    H0 = Hn.copy()
    nmed = 0
    for j, i in zip(*np.nonzero(core)):
        r2 = (P[:, 0] - X[j, i]) ** 2 + (P[:, 1] - Y[j, i]) ** 2
        near = r2 < NEAR ** 2
        if near.sum() >= 3:                                         # (points round the node: their median)
            Hn[j, i] = float(np.median(zt[near]))
            nmed += 1
            continue
        w = np.exp(-r2 / (2 * SIGMA ** 2))
        Hn[j, i] += float((w * d).sum() / (w.sum() + W0))
    free = shapely.contains_xy(unary_union([bank, lay.buffer(RING)]), X, Y) & ~core & ~keep
    if free.any():
        fill(free)
    dd = Hn - H0
    info = dict(points=len(PTS), core=int(core.sum()), by_median=nmed, eased=int(free.sum()),
                moved=(int((np.abs(dd) > 0.05).sum()), round(float(dd.min()), 2), round(float(dd.max()), 2)),
                photo_minus_game=round(float(np.median(d)), 2))
    return core | free, info


