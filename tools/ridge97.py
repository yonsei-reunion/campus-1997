def grid_z(x, y):
    """GRID, bilinear (on the working datum)"""
    x, y = np.broadcast_arrays(np.asarray(x, float), np.asarray(y, float))
    z = ndimage.map_coordinates(GRID, [(y.ravel() - GRID_Y0) / GRID_D, (x.ravel() - GRID_X0) / GRID_D], order=1, mode='nearest')
    return z.reshape(x.shape) if x.ndim else float(z[0])


def grade(Hn, X, Y, FIXED, halls, fill):
    """GRID in RIDGE (PEAK level), eased round it and between it and what the other blocks have laid (fill:
    harmonic_fill).  halls: the outlines of the halls that stay (not the 사택).  Returns the nodes set (to be FIXED)
    and a summary"""
    H0 = Hn.copy()
    step = float(X[0, 1] - X[0, 0])
    near_fixed = ndimage.distance_transform_edt(~FIXED) * step < KEEP_OFF
    stay = shapely.contains_xy(unary_union([h.buffer(HALL_PAD) for h in halls]), X, Y) if halls else np.zeros(X.shape, bool)
    stay |= (X < VALLEY_X) & (Y > 40.0) & (Y < 262.0)
    inr = shapely.contains_xy(RIDGE, X, Y)
    peak = shapely.contains_xy(PEAK, X, Y)
    peak_ring = shapely.contains_xy(PEAK.buffer(PEAK_EASE), X, Y) & ~peak
    core = inr & ~FIXED & ~near_fixed & ~stay & ~peak_ring
    Hn[core] = grid_z(X, Y)[core]
    Hn[peak & core] = PEAK_Z
    took = core.copy()
    free = (shapely.contains_xy(RIDGE.buffer(RING), X, Y) | peak_ring) & ~core & ~FIXED & ~stay
    if free.any():
        fill(free)
    d = Hn - H0
    info = dict(core=int(core.sum()), peak=int((peak & core).sum()), eased=int(free.sum()),
                moved=(int((np.abs(d) > 0.05).sum()), round(float(d.min()), 1), round(float(d.max()), 1)))
    return took | free, info


def trees_aside(trees, pad=2.0):
    """trees the random planting put on the cleared top (the scans have none on it): each moved in its place in the
    list to the nearest point pad m outside it, clear of the trees there by 3 m.  Returns the moves"""
    ring = PEAK.buffer(pad).exterior
    spots = [ring.interpolate(d) for d in np.arange(0.0, ring.length, 0.5)]
    inside = [t for t in trees if PEAK.buffer(1.0).contains(Point(t[1], t[2]))]
    near = [Point(t[1], t[2]) for t in trees if not any(t is i for i in inside) and abs(t[1] + 220.0) < 40 and abs(t[2] - 95.0) < 40]
    spots = [q for q in spots if all(q.distance(o) > 3.0 for o in near)]
    moved = []
    for t in inside:
        if not spots:
            break
        q = min(spots, key=lambda q_: q_.distance(Point(t[1], t[2])))
        moved.append((t[0], t[1], t[2], round(q.x, 2), round(q.y, 2)))
        t[1], t[2] = round(q.x, 2), round(q.y, 2)
        spots = [s_ for s_ in spots if s_.distance(q) > 3.5]
    return moved
