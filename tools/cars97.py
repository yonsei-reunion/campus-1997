import math

import numpy as np


def _frame(o, ang):
    a = math.radians(ang)
    t = np.array([math.cos(a), math.sin(a)])
    return np.asarray(o, float), t, np.array([-t[1], t[0]])


def _xy(fr, u, v):
    o, t, n = fr
    q = o + t * u + n * v
    return round(float(q[0]), 2), round(float(q[1]), 2)


