def lotb():
    """정문 동쪽 주차장: 칸 [(이름, x, y, 방향 rad)], 선 [[x0, y0, x1, y1]], 칸 밖 차 [(이름, x, y, 방향 rad, 크기, 밝기)]"""
    fr = _frame(*LOTB_FR)
    au = math.radians(LOTB_FR[1])
    stalls, lines = [], []
    for nm, uc, nose, v0, p, k, ua in LOTB_ROWS:
        uh = ua + nose * 5.0                                    # (칸 머리 쪽 끝)
        for i in range(k + 1):
            v = v0 + p * i
            lines.append([*_xy(fr, ua, v), *_xy(fr, uh, v)])
        lines.append([*_xy(fr, ua, v0), *_xy(fr, ua, v0 + p * k)])
        for i in range(k):
            stalls.append(('%s%d' % (nm, i), *_xy(fr, uc, v0 + p * (i + 0.5)), au + (0.0 if nose > 0 else math.pi)))
    more = [('more%d' % j, *_xy(fr, u, v), au + math.radians(h), s, w) for j, (u, v, h, s, w) in enumerate(LOTB_MORE)]
    return stalls, lines, more


